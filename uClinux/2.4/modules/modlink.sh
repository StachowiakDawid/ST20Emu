#!/bin/bash
# modlink.sh OUTDIR NAME KERNEL_MAP OBJ.o... (in the st20-build container)
# Links an ST20 kernel module (LIT objects compiled like kernel objects) twice, at
# 0x50000000 and 0x51000000, against the running kernel's symbols (linux.map entries for
# every name the objects use, as absolute ast assignments), plus libgcc for helpers the
# kernel lacks.  mkmod.py (host) diffs the two images into a relocatable .mod.
set -e
export PATH=/work/tools/bin:$PATH
out=$1 name=$2 map=$3; shift 3
mkdir -p $out
tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT
# names the module objects use or define
for o in "$@"; do litdump $o 2>/dev/null; done > $tmp/dump
sed -n 's/^.* is \(_[A-Za-z0-9_$.]*\), defined elsewhere$/\1/p' $tmp/dump | sort -u > $tmp/undef
sed -n 's/^.* is \(_[A-Za-z0-9_$.]*\), fragment defined here$/\1/p' $tmp/dump | sort -u > $tmp/def
comm -23 $tmp/undef $tmp/def > $tmp/need
initvar=$(grep '^___st20_ic__' $tmp/def | head -1)
exitvar=$(grep '^___st20_ec__' $tmp/def | head -1)
[ -n "$initvar" ] || { echo "modlink: no module_init() in $*" >&2; exit 1; }
{
  echo '// generated by modlink.sh: module entry stub + kernel symbols'
  echo '.text'; echo '.data'; echo '.bss'; echo '.text'
  # segments back to back: text, data, bss (as the kernel's head.ast)
  echo '.globl text@@start;'; echo '.globl text@@size;'; echo '.globl data@@size;'
  echo '.globl bss@@size;'; echo '.globl data@@start;'; echo '.globl bss@@start;'
  echo 'data@@start = text@@start + text@@size'
  echo 'bss@@start = data@@start + data@@size'
  echo '.globl @@hook;'; echo '.globl '"$initvar"';'
  [ -n "$exitvar" ] && echo '.globl '"$exitvar"';'
  echo '@@hook:'
  echo "	ldc $initvar-LM1"; echo '	ldpi'; echo 'LM1:'
  if [ -n "$exitvar" ]; then echo "	ldc $exitvar-LM2"; echo '	ldpi'; echo 'LM2:'; fi
  # (refer to the segment symbols so that lit lists them in the map for mkmod.py)
  echo '	ldc data@@start-LM3'; echo '	ldpi'; echo 'LM3:'
  echo '	ldc bss@@start-LM4'; echo '	ldpi'; echo 'LM4:'
  echo '	ldc text@@size'; echo '	ldc data@@size'; echo '	ldc bss@@size'
  echo '	ret'
  # kernel symbols: absolute values from the running kernel's map
  awk 'NR == FNR {need[$1] = 1; next} ($1 in need) && $1 !~ /@@/ {
         printf ".globl %s;\n%s = %d\n", $1, $1, $2 }' $tmp/need $map
} > $tmp/stub.s
cp $tmp/stub.s $out/$name.stub.s
ast -o $tmp/stub.o $tmp/stub.s
LIBGCC=$(t450-gcc -print-libgcc-file-name)
for base in 0x50000000 0x51000000; do
  lit -T $base -m$out/$name.$base.map $tmp/stub.o "$@" $LIBGCC -o $tmp/m.lit
  crossload -o $out/$name.$base.bin $tmp/m.lit
done
echo "$initvar $exitvar" > $out/$name.entry
