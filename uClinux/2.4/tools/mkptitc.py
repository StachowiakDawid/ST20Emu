#!/usr/bin/env python3
"""mkptitc.py OUT.h [SOURCE]: PTI transport-controller microcode for modules/dvb/pti.c.

The STi5512 PTI runs ST's microcode (PTI 3.4.1 "TC version 3.4.1", 729 words), which is
not part of this tree.  It is taken from the DSR9500 boot loader as recovered in
Decompilation/DSR9500/src/l_m_81ac.c (array pti_tc_code, loader address 0xc0602cd8),
or from SOURCE (that C file, or a raw little-endian 2916-byte dump).  Without a source
OUT.h is written empty and the driver starts the PTI without microcode (enough for
st20emu's high-level PTI model, not for real hardware)."""
import os, re, sys

out = sys.argv[1]
src = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
    os.path.dirname(os.path.abspath(__file__)),
    '../../../../Decompilation/DSR9500/src/l_m_81ac.c')
words = None
if os.path.exists(src):
    data = open(src, 'rb').read()
    if src.endswith('.c'):
        m = re.search(rb'pti_tc_code\[729\]\s*=\s*\{([^}]*)\}', data)
        if m:
            words = [int(w, 16) for w in re.findall(rb'0x[0-9a-fA-F]+', m.group(1))]
    elif len(data) == 729 * 4:
        words = [int.from_bytes(data[i:i + 4], 'little') for i in range(0, len(data), 4)]
with open(out, 'w') as f:
    f.write('/* generated by tools/mkptitc.py; do not edit */\n')
    if words and len(words) == 729:
        f.write('#define DVB_HAVE_PTI_TC 1\nstatic const u32 pti_tc_code[729] = {\n')
        for i in range(0, 729, 6):
            f.write('\t' + ', '.join('0x%08x' % w for w in words[i:i + 6]) + ',\n')
        f.write('};\n')
        print('mkptitc: %d words from %s' % (len(words), src))
    else:
        print('mkptitc: no microcode source (%s), PTI without TC code' % src)
