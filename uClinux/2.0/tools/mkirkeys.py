#!/usr/bin/env python3
"""IR remote keyboard for uClinux on the DSR9500: one key map, two outputs.

  include/asm-st20/irkeys.h   kernel table: NEC command byte -> bytes typed into ttyS0
  dsr9500-keyboard.ir         Flipper Zero remote (raw NEC frames, customer code 0xfe01)

NEC frames as the DSR9500 receiver expects them (st20emu src/board/DSR9500.cpp): customer
code 0xfe01, command byte, inverted command byte, LSB first; 9 ms mark + 4.5 ms space,
bits of 560 us mark + 560 (0) or 1690 (1) us space, 560 us stop mark; 38 kHz carrier.

Command bytes:
  0x00-0x1f  the DSR9500's own remote: digits, OK = Enter, Exit = Ctrl-C, arrows,
             P+/P- = PageUp/PageDown, Menu = Tab, Power = Esc
  0x20-0x7e  that ASCII character
  0x7f       Backspace (DEL, the tty's erase character)
  0x81-0x9a  Ctrl-A ... Ctrl-Z;  0x88 Backspace, 0x89 Tab, 0x8d Enter, 0x9b Esc
  0xa0-0xa9  Up, Down, Right, Left, Home, End, PageUp, PageDown, Delete, Insert

usage: mkirkeys.py HEADER IRFILE
"""
import sys

ESC = "\x1b"
KEYS = {}            # command -> (Flipper button name, bytes sent)


def key(cmd, name, text):
    assert cmd not in KEYS, hex(cmd)
    KEYS[cmd] = (name, text)


# the original remote (commands from st20emu's dsr9500IrKeys)
for d in range(10):
    key(d, f"Remote_{d}", str(d))
key(27, "Remote_OK", "\r")
key(24, "Remote_Exit", "\x03")
key(31, "Remote_Up", ESC + "[A")
key(30, "Remote_Down", ESC + "[B")
key(14, "Remote_Right", ESC + "[C")
key(13, "Remote_Left", ESC + "[D")
key(18, "Remote_PgUp", ESC + "[5~")
key(19, "Remote_PgDn", ESC + "[6~")
key(28, "Remote_Menu", "\t")
key(10, "Remote_Power", ESC)

# printable ASCII
NAMES = {" ": "Space"}
for c in range(0x20, 0x7f):
    ch = chr(c)
    key(c, NAMES.get(ch, ch), ch)
key(0x7f, "Backspace", "\x7f")

# control characters
for i, letter in enumerate("ABCDEFGHIJKLMNOPQRSTUVWXYZ"):
    code = 0x81 + i
    special = {0x88: ("Backspace_BS", "\x7f"), 0x89: ("Tab", "\t"), 0x8d: ("Enter", "\r")}
    name, text = special.get(code, (f"Ctrl_{letter}", chr(i + 1)))
    key(code, name, text)
key(0x9b, "Esc", ESC)

# cursor and editing keys
for i, (name, seq) in enumerate([("Up", "[A"), ("Down", "[B"), ("Right", "[C"), ("Left", "[D"),
                                  ("Home", "[1~"), ("End", "[4~"), ("PageUp", "[5~"),
                                  ("PageDown", "[6~"), ("Delete", "[3~"), ("Insert", "[2~")]):
    key(0xa0 + i, name, ESC + seq)


def c_string(text):
    out = ""
    for ch in text:
        o = ord(ch)
        out += ch if 0x20 <= o < 0x7f and ch not in '"\\?' else "\\%03o" % o
    return '"' + out + '"'


def header():
    lines = ["/* generated by tools/mkirkeys.py: NEC command -> bytes typed into ttyS0 */",
             "#ifndef _ST20_IRKEYS_H", "#define _ST20_IRKEYS_H", "",
             "static const char *const st20_ir_keymap[256] = {"]
    for cmd in range(256):
        if cmd in KEYS:
            name, text = KEYS[cmd]
            lines.append(f"\t/* 0x{cmd:02x} {name} */ {c_string(text)},")
        else:
            lines.append(f"\t/* 0x{cmd:02x} */ 0,")
    lines += ["};", "", "#endif", ""]
    return "\n".join(lines)


def nec_raw(command, customer=0xFE01):
    frame = customer | command << 16 | ((~command) & 0xFF) << 24
    timings = [9000, 4500]
    for bit in range(32):
        timings += [560, 1690 if (frame >> bit) & 1 else 560]
    timings.append(560)
    return " ".join(map(str, timings))


def flipper():
    out = ["Filetype: IR signals file", "Version: 1",
           "# uClinux on the Samsung DSR9500: IR remote keyboard (tools/mkirkeys.py)",
           "# NEC, customer code 0xFE01; raw frames so every Flipper firmware sends them alike"]
    order = sorted(KEYS, key=lambda c: (c < 0x20, c))      # keyboard keys first
    for cmd in order:
        name, _ = KEYS[cmd]
        out += ["#", f"name: {name}", "type: raw", "frequency: 38000", "duty_cycle: 0.330000",
                f"data: {nec_raw(cmd)}"]
    return "\n".join(out) + "\n"


def main():
    open(sys.argv[1], "w").write(header())
    open(sys.argv[2], "w").write(flipper())
    print(f"{len(KEYS)} keys -> {sys.argv[1]}, {sys.argv[2]}")


if __name__ == "__main__":
    main()
